using System.Globalization;
using System.Text;
using Deguffer.Core.Choosing;
using Deguffer.Core.Providers;
using Deguffer.Core.Safety;

namespace Deguffer.Core.Tests;

/// <summary>
/// The wiki's list of supported providers, written from the providers themselves so that the list
/// cannot name a row the product does not ship, or miss one it does.
///
/// <para>Grouped as the list of what to scan groups them (<see cref="ProviderListing.Group"/>), so a
/// reader finds a row under the heading they see in the application.</para>
/// </summary>
internal static class SupportedProvidersPage
{
    /// <summary>Where the page's source is kept, relative to the repository root.</summary>
    public const string RelativePath = "docs/wiki/Supported-providers.md";

    private const string CacheLocations = "https://github.com/BootBlock/Deguffer/blob/main/docs/cache-locations.md";

    public static string Render(IEnumerable<ICleanupProvider> providers)
    {
        var groups = ProviderListing.Group(providers, search: null);
        var count = groups.Sum(group => group.Providers.Count);
        var page = new StringBuilder();

        page.Append(CultureInfo.InvariantCulture, $"""
            <!-- Generated by SupportedProvidersPageTests from the providers Deguffer ships. Do not edit by hand. -->

            # Supported providers

            Deguffer knows {count} locations. Each one is a *provider*: a single class that names one cache,
            log or leftover, the tool that writes it, and the children it recognises. Anything a provider
            does not recognise is left alone.

            The tiers say what deleting costs you:

            | Tier | Meaning |
            | --- | --- |
            {TierRows()}

            A **Researched** provider was written from the publisher's documentation and reports from users,
            not from a real installation. It keeps every safety rule, but it is never pre-selected.

            For where each location is, how Deguffer cleans it and what the next use costs, see
            [What Deguffer cleans, and what it costs you]({CacheLocations}).

            """);

        foreach (var group in groups)
        {
            page.Append(CultureInfo.InvariantCulture, $"""

                ## {ProviderListing.Title(group.Category)}

                | Location | Application | Publisher | Tier | Basis |
                | --- | --- | --- | --- | --- |

                """);

            foreach (var provider in group.Providers)
            {
                page.Append(CultureInfo.InvariantCulture,
                    $"| {Cell(provider.Name)} | {Cell(provider.Description.Application)} "
                    + $"| {Cell(provider.Description.Publisher)} | {(int)provider.Tier} "
                    + $"| {provider.Basis.ToDisplayName()} |\n");
            }
        }

        return page.ToString().ReplaceLineEndings("\n");
    }

    private static string TierRows() => string.Join(
        "\n",
        Enum.GetValues<SafetyTier>()
            .Where(tier => tier.IsOfferable())
            .Select(tier => $"| {(int)tier} | {tier.ToDisplayName()}: {tier.ToCleaningAdvice()}. |"));

    // A pipe ends a table cell and a line break ends the row, so either inside a name would split it.
    private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal).ReplaceLineEndings(" ");
}
